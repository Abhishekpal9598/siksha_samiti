<#
.SYNOPSIS
  Automated MongoDB Database Restore Script for Education Committee Examination Portal
.DESCRIPTION
  Restores a database from a compressed mongodump archive.
.PARAMETER ArchivePath
  Path to .gz archive file generated by backup_database.ps1
.PARAMETER Uri
  MongoDB connection URI (defaults to MONGODB_URI env var or local)
#>

[CmdletBinding()]
param (
  [Parameter(Mandatory = $true)]
  [string]$ArchivePath,
  [string]$Uri = $env:MONGODB_URI
)

if (-not $Uri) {
  $Uri = "mongodb://127.0.0.1:27017/education_committee"
}

if (-not (Test-Path $ArchivePath)) {
  Write-Host "[ERROR] Archive file not found: $ArchivePath" -ForegroundColor Red
  exit 1
}

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host " Education Committee Examination Portal — Database Restore" -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "Source Archive: $ArchivePath"
Write-Host "Target Target : MongoDB"

$RestoreCmd = Get-Command "mongorestore" -ErrorAction SilentlyContinue

if ($RestoreCmd) {
  Write-Host "Restoring database from archive..."
  & mongorestore --uri="$Uri" --archive="$ArchivePath" --gzip --drop
  if ($LASTEXITCODE -eq 0) {
    Write-Host "[SUCCESS] Database restoration completed successfully!" -ForegroundColor Green
  } else {
    Write-Host "[ERROR] mongorestore exited with code $LASTEXITCODE" -ForegroundColor Red
    exit 1
  }
} else {
  Write-Host "[WARN] 'mongorestore' command not found in PATH." -ForegroundColor Yellow
  Write-Host "       Example direct command:" -ForegroundColor Yellow
  Write-Host "       mongorestore --uri=`"$Uri`" --archive=`"$ArchivePath`" --gzip --drop" -ForegroundColor DarkGray
  exit 1
}
